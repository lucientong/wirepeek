#include <wirepeek/dissector/dissect.h>

#include <array>
#include <benchmark/benchmark.h>
#include <cstdint>

namespace {

constexpr std::array<uint8_t, 54> kTcpPacket = {
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0x08, 0x00,
    0x45, 0x00, 0x00, 0x28, 0x00, 0x00, 0x40, 0x00, 0x40, 0x06, 0x00, 0x00, 0xc0, 0xa8,
    0x01, 0x01, 0x0a, 0x00, 0x00, 0x01, 0x30, 0x39, 0x00, 0x50, 0x00, 0x00, 0x00, 0x01,
    0x00, 0x00, 0x00, 0x00, 0x50, 0x02, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00,
};

void BM_DissectTcp(benchmark::State& state) {
  const wirepeek::PacketView packet{
      .data = kTcpPacket,
      .capture_length = static_cast<uint32_t>(kTcpPacket.size()),
      .original_length = static_cast<uint32_t>(kTcpPacket.size()),
  };
  for (auto _ : state) {
    benchmark::DoNotOptimize(wirepeek::dissector::Dissect(packet));
  }
}

BENCHMARK(BM_DissectTcp);

}  // namespace

BENCHMARK_MAIN();
